-- 4e: Stale documents (LASTMOD older than 180 days)
SELECT
  COUNT_IF(DATEDIFF('day', COALESCE(LASTMOD, FIRST_SEEN_AT)::DATE, CURRENT_DATE()) >= 180) AS STALE_COUNT,
  COUNT(*) AS TOTAL_WITH_LASTMOD,
  COALESCE(
    COUNT_IF(DATEDIFF('day', COALESCE(LASTMOD, FIRST_SEEN_AT)::DATE, CURRENT_DATE()) >= 180) 
    / NULLIF(COUNT(*), 0),
    0
  )::FLOAT AS STALE_PCT
FROM IDENTIFIER('{DOCS_MASTER}');
